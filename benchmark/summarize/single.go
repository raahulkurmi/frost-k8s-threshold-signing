package main

// Phase 7A single-host summary (-single DIR). DIR holds run<k>/<label>.csv
// (one tokenbench CSV per configuration and run) and run<k>/<label>.metrics.json
// (host CPU utilisation and load average sampled over that configuration).
// Labels: B0-c<C>, B1-c<C>, T-<strategy>-<fanout>-c<C>.
//
// Output: per-configuration rows for every run, the median across runs, a
// B0/B1/T comparison per concurrency, and the N49 check with thresholds fixed
// here before any 7A data existed:
//   N49-1 goodput(c=50) >= 0.8 x goodput(c=10)
//   N49-2 error rate at c=10 <= 1%
//   N49-3 failed-request p95 at c=50 <= 2.2 s (deadline 2 s + 10%) and
//         successful p95 at c=50 <= 2 s

import (
	"encoding/json"
	"fmt"
	"math"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type metrics struct {
	CPUBusyPct  float64 `json:"cpu_busy_pct"`
	CPUStealPct float64 `json:"cpu_steal_pct"`
	Load1       float64 `json:"load1"`
	Load5       float64 `json:"load5"`
}

type cell struct {
	run string
	st  *stats
	m   *metrics
}

var singleRe = regexp.MustCompile(`^(.*)-c(\d+)$`)

func median(xs []float64) float64 {
	var v []float64
	for _, x := range xs {
		if !math.IsNaN(x) {
			v = append(v, x)
		}
	}
	if len(v) == 0 {
		return math.NaN()
	}
	sort.Float64s(v)
	if len(v)%2 == 1 {
		return v[len(v)/2]
	}
	return (v[len(v)/2-1] + v[len(v)/2]) / 2
}

func errPct(s *stats) float64 { return 100 * float64(s.errs) / float64(s.n) }

func runSingle(dir, title, note, outPath string) error {
	runs, _ := filepath.Glob(filepath.Join(dir, "run*"))
	sort.Strings(runs)
	byCfg := map[string][]cell{} // config label (with -c) -> cells
	var cfgs []string
	var sources []string
	for _, rd := range runs {
		run := filepath.Base(rd)
		csvs, _ := filepath.Glob(filepath.Join(rd, "*.csv"))
		sort.Strings(csvs)
		for _, p := range csvs {
			sts, err := load(run, p)
			if err != nil {
				return err
			}
			sources = append(sources, "- `"+strings.TrimPrefix(p, dir+"/")+"`")
			var m *metrics
			if b, err := os.ReadFile(strings.TrimSuffix(p, ".csv") + ".metrics.json"); err == nil {
				m = &metrics{}
				if json.Unmarshal(b, m) != nil {
					m = nil
				}
			}
			for _, s := range sts {
				if _, ok := byCfg[s.label]; !ok {
					cfgs = append(cfgs, s.label)
				}
				byCfg[s.label] = append(byCfg[s.label], cell{run, s, m})
			}
		}
	}
	if len(cfgs) == 0 {
		return fmt.Errorf("no CSVs under %s/run*/", dir)
	}
	sysOf := func(l string) (string, int) {
		m := singleRe.FindStringSubmatch(l)
		if m == nil {
			return l, -1
		}
		c, _ := strconv.Atoi(m[2])
		return m[1], c
	}
	sort.SliceStable(cfgs, func(i, j int) bool {
		si, ci := sysOf(cfgs[i])
		sj, cj := sysOf(cfgs[j])
		if si != sj {
			return si < sj
		}
		return ci < cj
	})
	agg := func(l string, f func(c cell) float64) float64 {
		var xs []float64
		for _, c := range byCfg[l] {
			xs = append(xs, f(c))
		}
		return median(xs)
	}
	mf := func(f func(m *metrics) float64) func(c cell) float64 {
		return func(c cell) float64 {
			if c.m == nil {
				return math.NaN()
			}
			return f(c.m)
		}
	}

	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", title)
	if note != "" {
		fmt.Fprintf(&b, "> %s\n\n", note)
	}
	fmt.Fprintf(&b, "Generated by `benchmark/summarize -single` from the raw CSVs and metrics files listed at the end; nothing is typed by hand. Latencies in ms over successful requests (nearest-rank percentiles). **Goodput** = successful tokens / whole-run window. \"median of runs\" = median over the %d runs of each run's statistic. CPU = host CPU busy %% (all vCPUs, from /proc/stat over the configuration's measured window, incl. warm-up); load = 1-min load average at its end.\n\n", len(runs))

	// Comparison per concurrency (median of runs).
	var concs []int
	seenC := map[int]bool{}
	var systems []string
	seenS := map[string]bool{}
	for _, l := range cfgs {
		s, c := sysOf(l)
		if !seenC[c] {
			seenC[c] = true
			concs = append(concs, c)
		}
		if !seenS[s] {
			seenS[s] = true
			systems = append(systems, s)
		}
	}
	sort.Ints(concs)
	fmt.Fprintf(&b, "## B0 vs B1 vs T (median of runs)\n\nEach cell: median / p95 ms, error %%, goodput tokens/s, CPU busy %%. Overhead columns compare median latency.\n\n| System |")
	for _, c := range concs {
		fmt.Fprintf(&b, " c=%d |", c)
	}
	fmt.Fprintf(&b, "\n|---|")
	for range concs {
		fmt.Fprintf(&b, "---|")
	}
	fmt.Fprintln(&b)
	for _, s := range systems {
		fmt.Fprintf(&b, "| %s |", s)
		for _, c := range concs {
			l := fmt.Sprintf("%s-c%d", s, c)
			if _, ok := byCfg[l]; !ok {
				fmt.Fprintf(&b, " – |")
				continue
			}
			fmt.Fprintf(&b, " %s / %s, %s%% err, **%s**/s, CPU %s%% |",
				f1(agg(l, func(c cell) float64 { return c.st.median })), f1(agg(l, func(c cell) float64 { return c.st.p95 })),
				f1(agg(l, func(c cell) float64 { return errPct(c.st) })), f1(agg(l, func(c cell) float64 { return c.st.goodput })),
				f1(agg(l, mf(func(m *metrics) float64 { return m.CPUBusyPct }))))
		}
		fmt.Fprintln(&b)
	}
	fmt.Fprintf(&b, "\n### Median-latency overhead (median of runs)\n\n| System | vs | ")
	for _, c := range concs {
		fmt.Fprintf(&b, "c=%d | ", c)
	}
	fmt.Fprintf(&b, "\n|---|---|")
	for range concs {
		fmt.Fprintf(&b, "---:|")
	}
	fmt.Fprintln(&b)
	for _, s := range systems {
		for _, base := range []string{"B0", "B1"} {
			if s == base || (s == "B0" && base == "B1") {
				continue
			}
			fmt.Fprintf(&b, "| %s | %s |", s, base)
			for _, c := range concs {
				x := agg(fmt.Sprintf("%s-c%d", s, c), func(c cell) float64 { return c.st.median })
				y := agg(fmt.Sprintf("%s-c%d", base, c), func(c cell) float64 { return c.st.median })
				if math.IsNaN(x) || math.IsNaN(y) || y == 0 {
					fmt.Fprintf(&b, " – |")
				} else {
					fmt.Fprintf(&b, " %+.1f ms (%.2f×) |", x-y, x/y)
				}
			}
			fmt.Fprintln(&b)
		}
	}

	// N49 check for every T variant.
	fmt.Fprintf(&b, "\n## N49 check (T variants; thresholds fixed before the run)\n\nN49-1 goodput(c=50) ≥ 0.8 × goodput(c=10); N49-2 error rate at c=10 ≤ 1%%; N49-3 failed p95 at c=50 ≤ 2200 ms and successful p95 at c=50 ≤ 2000 ms. Values are medians of runs; a criterion with no data is FAIL.\n\n| T variant | goodput c10 | goodput c50 | ratio | N49-1 | err%% c10 | N49-2 | failed p95 c50 | ok p95 c50 | N49-3 |\n|---|---:|---:|---:|---|---:|---|---:|---:|---|\n")
	pf := func(ok bool) string {
		if ok {
			return "PASS"
		}
		return "**FAIL**"
	}
	for _, s := range systems {
		if !strings.HasPrefix(s, "T-") {
			continue
		}
		l10, l50 := s+"-c10", s+"-c50"
		g10 := agg(l10, func(c cell) float64 { return c.st.goodput })
		g50 := agg(l50, func(c cell) float64 { return c.st.goodput })
		e10 := agg(l10, func(c cell) float64 { return errPct(c.st) })
		fp := agg(l50, func(c cell) float64 { return c.st.failP95 })
		op := agg(l50, func(c cell) float64 { return c.st.p95 })
		ratio := g50 / g10
		fpOK := math.IsNaN(fp) || fp <= 2200 // no failures at all is a pass
		fmt.Fprintf(&b, "| %s | %s | %s | %.2f | %s | %s | %s | %s | %s | %s |\n", s, f1(g10), f1(g50), ratio,
			pf(!math.IsNaN(ratio) && ratio >= 0.8), f1(e10), pf(!math.IsNaN(e10) && e10 <= 1),
			f1(fp), f1(op), pf(fpOK && !math.IsNaN(op) && op <= 2000))
	}

	// Every run of every configuration.
	fmt.Fprintf(&b, "\n## All configurations, every run\n\n| Configuration | Run | N | errors | error %% | median | p95 | p99 | mean | stddev | min | max | goodput (ok/s) | offered (all/s) | failed p95 | CPU busy %% | CPU steal %% | load1 | load5 |\n|---|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	var errNotes []string
	for _, l := range cfgs {
		for _, c := range byCfg[l] {
			s := c.st
			mb, ms, l1, l5 := math.NaN(), math.NaN(), math.NaN(), math.NaN()
			if c.m != nil {
				mb, ms, l1, l5 = c.m.CPUBusyPct, c.m.CPUStealPct, c.m.Load1, c.m.Load5
			}
			fmt.Fprintf(&b, "| %s | %s | %d | %d | %.1f | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
				l, c.run, s.n, s.errs, errPct(s), f1(s.median), f1(s.p95), f1(s.p99), f1(s.mean), f1(s.stddev), f1(s.min), f1(s.max),
				f1(s.goodput), f1(s.offered), f1(s.failP95), f1(mb), f1(ms), f1(l1), f1(l5))
			if s.errs > 0 {
				errNotes = append(errNotes, fmt.Sprintf("- `%s/%s`: %d errors; first: `%s`", c.run, l, s.errs, s.firstErr))
			}
		}
	}
	if len(errNotes) > 0 {
		fmt.Fprintf(&b, "\nErrors:\n%s\n", strings.Join(errNotes, "\n"))
	}
	fmt.Fprintf(&b, "\nSource CSVs (under `%s`):\n%s\n", dir, strings.Join(sources, "\n"))
	return os.WriteFile(outPath, []byte(b.String()), 0o644)
}

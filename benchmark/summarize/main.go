// Command summarize turns tokenbench CSVs into summary.md. Every number in
// summary.md is computed here from the raw rows; nothing is typed by hand.
//
//	summarize -title "..." -note "..." -out summary.md run1.csv run2.csv ...
package main

import (
	"encoding/csv"
	"flag"
	"fmt"
	"io"
	"math"
	"os"
	"sort"
	"strconv"
	"strings"
)

type stats struct {
	label                                    string
	n, errs                                  int
	median, p95, p99, mean, stddev, min, max float64 // ms
	throughput                               float64 // successful req/s over the measured wall window
	firstErr                                 string
}

func pct(sorted []float64, p float64) float64 {
	if len(sorted) == 0 {
		return math.NaN()
	}
	// nearest-rank
	k := int(math.Ceil(p/100*float64(len(sorted)))) - 1
	if k < 0 {
		k = 0
	}
	return sorted[k]
}

func load(path string) (map[string]*stats, []string, error) {
	f, err := os.Open(path)
	if err != nil {
		return nil, nil, err
	}
	defer f.Close()
	r := csv.NewReader(f)
	hdr, err := r.Read()
	if err != nil || strings.Join(hdr, ",") != "label,seq,start_unix_ns,latency_ns,ok,error" {
		return nil, nil, fmt.Errorf("%s: unexpected header %v", path, hdr)
	}
	lat := map[string][]float64{}
	first, last := map[string]int64{}, map[string]int64{}
	out := map[string]*stats{}
	var order []string
	for {
		rec, err := r.Read()
		if err == io.EOF {
			break
		}
		if err != nil {
			return nil, nil, err
		}
		l := rec[0]
		st, ok := out[l]
		if !ok {
			st = &stats{label: l}
			out[l] = st
			order = append(order, l)
		}
		st.n++
		start, _ := strconv.ParseInt(rec[2], 10, 64)
		ln, _ := strconv.ParseInt(rec[3], 10, 64)
		if rec[4] != "1" {
			st.errs++
			if st.firstErr == "" {
				st.firstErr = rec[5]
			}
			continue
		}
		lat[l] = append(lat[l], float64(ln)/1e6)
		if first[l] == 0 || start < first[l] {
			first[l] = start
		}
		if e := start + ln; e > last[l] {
			last[l] = e
		}
	}
	for l, st := range out {
		xs := lat[l]
		sort.Float64s(xs)
		if len(xs) == 0 {
			continue
		}
		var sum float64
		for _, x := range xs {
			sum += x
		}
		st.mean = sum / float64(len(xs))
		var sq float64
		for _, x := range xs {
			sq += (x - st.mean) * (x - st.mean)
		}
		if len(xs) > 1 {
			st.stddev = math.Sqrt(sq / float64(len(xs)-1))
		}
		st.median, st.p95, st.p99 = pct(xs, 50), pct(xs, 95), pct(xs, 99)
		st.min, st.max = xs[0], xs[len(xs)-1]
		if w := float64(last[l]-first[l]) / 1e9; w > 0 {
			st.throughput = float64(len(xs)) / w
		}
	}
	return out, order, nil
}

func main() {
	title := flag.String("title", "Benchmark summary", "title")
	note := flag.String("note", "", "labelling note printed under the title")
	outPath := flag.String("out", "summary.md", "output")
	flag.Parse()
	var b strings.Builder
	fmt.Fprintf(&b, "# %s\n\n", *title)
	if *note != "" {
		fmt.Fprintf(&b, "> %s\n\n", *note)
	}
	fmt.Fprintf(&b, "Generated by `benchmark/summarize` from the raw CSVs listed below. Latencies in ms; percentiles are nearest-rank over successful requests; throughput = successful requests / (last end − first start). Every configuration run is listed, including the worst.\n\n")
	fmt.Fprintf(&b, "| Configuration | N | errors | median | p95 | p99 | mean | stddev | min | max | throughput (req/s) |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	var errNotes []string
	for _, p := range flag.Args() {
		m, order, err := load(p)
		if err != nil {
			fmt.Fprintln(os.Stderr, "summarize:", err)
			os.Exit(1)
		}
		for _, l := range order {
			s := m[l]
			fmt.Fprintf(&b, "| %s | %d | %d | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f | %.1f |\n",
				s.label, s.n, s.errs, s.median, s.p95, s.p99, s.mean, s.stddev, s.min, s.max, s.throughput)
			if s.errs > 0 {
				errNotes = append(errNotes, fmt.Sprintf("- `%s`: %d errors; first: `%s`", s.label, s.errs, s.firstErr))
			}
		}
	}
	if len(errNotes) > 0 {
		fmt.Fprintf(&b, "\nErrors:\n%s\n", strings.Join(errNotes, "\n"))
	}
	fmt.Fprintf(&b, "\nSource CSVs:\n")
	for _, p := range flag.Args() {
		fmt.Fprintf(&b, "- `%s`\n", p[strings.LastIndex(p, "/")+1:])
	}
	if err := os.WriteFile(*outPath, []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "summarize:", err)
		os.Exit(1)
	}
}

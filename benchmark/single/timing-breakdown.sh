#!/usr/bin/env bash
# benchmark/single/timing-breakdown.sh: where does a TokenRequest's time go
# (NOTES N64)? Run ON a Linux host with a kept e2e stack (`make e2e-keep`).
# For each concurrency: tokenbench (client-go CreateToken, WARMUP discarded),
# then the nginx timing lines and the coordinators' Sign lines of that window,
# joined exactly by nginx request_id. Writes breakdown.md (generated here, no
# hand-typed numbers) plus the raw CSV/JSONL per concurrency.
#
# Segments per joined request (ms):
#   nginx total     = nginx $request_time (request in -> response out at nginx)
#   nginx->coord    = coordinator gRPC handler arrival - nginx proxy time ($msec)
#   queued          = coordinator Sign start - handler arrival
#   coordinator     = Sign latency_ms (fan-out, verification, combine)
#   nginx rest      = nginx total - nginx->coord - queued - coordinator
# Client-side (distribution only, not joined): client total from the CSV;
# "outside nginx" = client median - nginx-total median (kube-apiserver, client).
set -euo pipefail
cd "$(dirname "$0")/../.."
REPO="$(pwd)"
export PATH="/usr/local/go/bin:$PATH"
N="${N:-200}" WARMUP="${WARMUP:-20}" CONCS="${CONCS:-1 10 50}"
COMPOSE=(docker compose -p tk8s -f deploy/docker-compose.yml)
kubectl --context kind-tk8s get --raw /readyz >/dev/null || { echo "no kept cluster: run make e2e-keep first" >&2; exit 1; }
SHA="$(git rev-parse HEAD)"; TS="$(date -u +%Y%m%dT%H%M%SZ)"
OUT="benchmark/results/$TS-${SHA:0:7}-timing-breakdown"; mkdir -p "$OUT"
( cd benchmark && go build -o "$REPO/bin/tokenbench" ./tokenbench )
STRAT="$("${COMPOSE[@]}" logs --no-color --no-log-prefix grpc-proxy-1 2>/dev/null | grep '"coordinator ready"' | tail -1 | jq -r '"\(.strategy) / fanout \(.fanout)"')"

med_p95() { # jq path over a JSON array on stdin -> "median p95"
  jq -r "map($1) | map(select(. != null)) | sort | if length == 0 then \"– –\" else \"\(.[(length*0.5|floor)]) \(.[((length*0.95|ceil)-1)])\" end"
}
{
  echo "# TokenRequest timing breakdown (N64)"
  echo
  echo "Generated by \`benchmark/single/timing-breakdown.sh\` on $(hostname) ($(nproc) vCPU), commit \`${SHA:0:7}\`, $(date -u +%FT%TZ). Coordinators: $STRAT. N=$N after $WARMUP warm-up per concurrency. Median / p95 in ms; nginx and coordinator lines joined by nginx request_id (warm-up excluded by time)."
  echo
  echo "| c | client total | nginx total | nginx→coordinator | queued before Sign | coordinator Sign | nginx rest | outside nginx (client median − nginx median) | joined / measured |"
  echo "|---:|---|---|---|---|---|---|---:|---|"
} > "$OUT/breakdown.md"
for c in $CONCS; do
  since="$(date -u +%Y-%m-%dT%H:%M:%S.%NZ)"
  bin/tokenbench -context kind-tk8s -n "$N" -warmup "$WARMUP" -c "$c" -label "c$c" -out "$OUT/c$c.csv" >/dev/null
  sleep 1
  "${COMPOSE[@]}" logs --no-color --no-log-prefix --since "$since" coordinator-lb 2>/dev/null | grep '"src":"nginx"' | jq -c 'select(.uri | endswith("/Sign"))' > "$OUT/c$c.nginx.jsonl" || true
  "${COMPOSE[@]}" logs --no-color --no-log-prefix --since "$since" grpc-proxy-1 grpc-proxy-2 grpc-proxy-3 2>/dev/null | grep -E '"msg":"(signed|sign failed)"' > "$OUT/c$c.coord.jsonl" || true
  first_ns="$(tail -n +2 "$OUT/c$c.csv" | cut -d, -f3 | sort -n | head -1)"
  jq -s --slurpfile ng "$OUT/c$c.nginx.jsonl" --argjson t0 "$first_ns" '
    ($ng | map({(.request_id): .}) | add // {}) as $by
    | map(select(.nginx_request_id != null and $by[.nginx_request_id] != null)
          | . as $c | $by[$c.nginx_request_id] as $n
          | ($n.msec | tonumber) as $end | ($n.request_time | tonumber) as $rt
          | select((($end - $rt) * 1e9) >= $t0)
          | {total: ($rt * 1000), n2c: $c.nginx_to_coordinator_ms, q: $c.queued_before_sign_ms, coord: $c.latency_ms,
             rest: (($rt * 1000) - $c.nginx_to_coordinator_ms - $c.queued_before_sign_ms - $c.latency_ms)})' "$OUT/c$c.coord.jsonl" > "$OUT/c$c.joined.json"
  client="$(tail -n +2 "$OUT/c$c.csv" | awk -F, '$5=="1"{print $4/1e6}' | jq -s . | med_p95 .)"
  total="$(med_p95 .total < "$OUT/c$c.joined.json")"; n2c="$(med_p95 .n2c < "$OUT/c$c.joined.json")"
  q="$(med_p95 .q < "$OUT/c$c.joined.json")"; co="$(med_p95 .coord < "$OUT/c$c.joined.json")"; rest="$(med_p95 .rest < "$OUT/c$c.joined.json")"
  outside="$(awk -v a="${client%% *}" -v b="${total%% *}" 'BEGIN{ if (a=="–"||b=="–") print "–"; else printf "%.1f", a-b }')"
  njoin="$(jq length "$OUT/c$c.joined.json")"; nmeas="$(tail -n +2 "$OUT/c$c.csv" | grep -c .)"
  f() { awk '{ if ($1=="–") print "–"; else printf "%.1f / %.1f", $1, $2 }' <<<"$1"; }
  echo "| $c | $(f "$client") | $(f "$total") | $(f "$n2c") | $(f "$q") | $(f "$co") | $(f "$rest") | $outside | $njoin / $nmeas |" >> "$OUT/breakdown.md"
done
cat "$OUT/breakdown.md"
echo "results: $OUT"

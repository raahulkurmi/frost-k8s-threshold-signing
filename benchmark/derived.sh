#!/usr/bin/env bash
# benchmark/derived.sh RESULTS_DIR: script-generated tables for numbers that the
# docs quote but summary.md does not contain (Phase 12 audit G-19; README rule
# "every number quoted anywhere must have a row in a script-generated summary").
# It reads only committed raw data and writes RESULTS_DIR/derived.md:
#   - coordinator-host CPU busy % per configuration (*.metrics.json,
#     coordinator_cpu_busy_pct), when present;
#   - per coordinator log (*.coord.jsonl.gz): signed tokens and how many signers
#     each contacted (signers_contacted), i.e. how often hedged fan-out fired.
# summary.md is never modified.
set -euo pipefail
dir="${1:?usage: benchmark/derived.sh RESULTS_DIR}"
[[ -d "$dir" ]] || { echo "derived.sh: $dir is not a directory" >&2; exit 1; }
command -v jq >/dev/null || { echo "derived.sh: jq not found" >&2; exit 1; }
out="$dir/derived.md"
{
  echo "# Derived tables for \`$(basename "$dir")\`"
  echo
  echo "Generated by \`benchmark/derived.sh\` from the raw files in this directory (audit G-19)."
  echo "Every value is computed here from the raw data; nothing is copied from a document."
  metrics="$(find "$dir" -name '*.metrics.json' | LC_ALL=C sort)"
  if [[ -n "$metrics" ]] && jq -e 'has("coordinator_cpu_busy_pct")' "$(echo "$metrics" | head -1)" >/dev/null 2>&1; then
    echo
    echo "## Coordinator-host CPU busy % per configuration"
    echo
    echo "| configuration (metrics file) | coordinator CPU busy % | steal % |"
    echo "|---|---:|---:|"
    for f in $metrics; do
      jq -r --arg f "${f#"$dir"/}" '"| \($f) | \(.coordinator_cpu_busy_pct // "–") | \(.coordinator_cpu_steal_pct // "–") |"' "$f"
    done
  fi
  logs="$(find "$dir" -name '*.coord.jsonl.gz' | LC_ALL=C sort)"
  if [[ -n "$logs" ]]; then
    echo
    echo "## Signers contacted per signed token (coordinator log)"
    echo
    echo "| coordinator log | signed tokens | contacted 5 | contacted 4 | contacted ≤ 3 | fanout |"
    echo "|---|---:|---:|---:|---:|---|"
    for f in $logs; do
      gunzip -c "$f" | jq -r 'select(.msg=="signed") | [.signers_contacted, .fanout] | @tsv' |
        awk -F'\t' -v f="${f#"$dir"/}" '{n++; if($1==5)c5++; else if($1==4)c4++; else lo++; fo[$2]=1}
          END{fs=""; for(k in fo) fs=fs (fs==""?"":",") k; printf "| %s | %d | %d | %d | %d | %s |\n", f, n, c5, c4, lo, fs}'
    done
  fi
} > "$out"
echo "wrote $out"
